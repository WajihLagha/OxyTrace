      tumeurLocalisation: entity.tumeurLocalisation,
      ronflement: entity.ronflement,
      dysphonie: entity.dysphonie,
      dysphagie: entity.dysphagie,
      acteOperatoire: entity.acteOperatoire,
      scoreStopbang: entity.scoreStopbang,
      mallampati: entity.mallampati,
