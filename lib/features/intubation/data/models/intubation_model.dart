      mobiliteCervicale: entity.mobiliteCervicale,
      macroglossie: entity.macroglossie,
      scoreAsa: entity.scoreAsa,
      intubationPrevue: entity.intubationPrevue,
      typeIntubation: entity.typeIntubation,
      nombreTentatives: entity.nombreTentatives,
      videolaryngoscope: entity.videolaryngoscope,
      guideEichmann: entity.guideEichmann,
      scoreCormack: entity.scoreCormack,
      intubationDifficileReelle: entity.intubationDifficileReelle,
      complications: entity.complications,
      photoPaths: entity.photoPaths,
      audioPath: entity.audioPath,
    );
  }

  Map<String, dynamic> toMap() {
    final map = <String, dynamic>{
      'patient_id': patientId,
      'created_at': createdAt.toIso8601String(),
      'updated_at': updatedAt.toIso8601String(),
      'antecedent_intubation_difficile':
          antecedentIntubationDifficile ? 1 : 0,
      'saos': saos ? 1 : 0,
      'diabete': diabete ? 1 : 0,
      'goitre': goitre ? 1 : 0,
      'maladie_rhumatismale': maladieRhumatismale ? 1 : 0,
      'traumatisme_cervical': traumatismeCervical ? 1 : 0,
      'brulure_cervico_faciale': brulureCervicoFaciale ? 1 : 0,
      'brulure_localisation': brulureLocalisation,
      'dysmorphie_cranio_faciale': dysmorphieCranioFaciale ? 1 : 0,
      'dysmorphie_localisation': dysmorphieLocalisation,
      'tumeur_cervicofaciale': tumeurCervicofaciale ? 1 : 0,
      'tumeur_localisation': tumeurLocalisation,
      'ronflement': ronflement ? 1 : 0,
      'dysphonie': dysphonie ? 1 : 0,
      'dysphagie': dysphagie ? 1 : 0,
      'acte_operatoire': acteOperatoire,
      'score_stopbang': scoreStopbang,
      'mallampati': mallampati,
      'dtm': dtm,
      'ouverture_buccale': ouvertureBuccale,
      'tour_de_cou': tourDeCou,
      'mobilite_cervicale': mobiliteCervicale,
      'macroglossie': macroglossie ? 1 : 0,
      'score_asa': scoreAsa,
      'intubation_prevue': intubationPrevue,
      'type_intubation': typeIntubation,
      'nombre_tentatives': nombreTentatives,
      'videolaryngoscope': videolaryngoscope ? 1 : 0,
      'guide_eichmann': guideEichmann ? 1 : 0,
      'score_cormack': scoreCormack,
      'intubation_difficile_reelle': intubationDifficileReelle ? 1 : 0,
      'complications': complications,
      'photo_paths': jsonEncode(photoPaths),
      'audio_path': audioPath,
    };

    if (id != null) {
      map['id'] = id;
    }

    return map;
  }

  factory IntubationModel.fromMap(Map<String, dynamic> map) {
    final rawPhotos = map['photo_paths'] as String?;
    final decodedPhotos = rawPhotos == null || rawPhotos.isEmpty
        ? <String>[]
        : List<String>.from(jsonDecode(rawPhotos) as List<dynamic>);

    return IntubationModel(
      id: map['id'] as int?,
      patientId: map['patient_id'] as int,
      createdAt: DateTime.parse(map['created_at'] as String),
      updatedAt: DateTime.parse(map['updated_at'] as String),
      antecedentIntubationDifficile:
          (map['antecedent_intubation_difficile'] as int? ?? 0) == 1,
      saos: (map['saos'] as int? ?? 0) == 1,
      diabete: (map['diabete'] as int? ?? 0) == 1,
      goitre: (map['goitre'] as int? ?? 0) == 1,
      maladieRhumatismale:
          (map['maladie_rhumatismale'] as int? ?? 0) == 1,
      traumatismeCervical:
          (map['traumatisme_cervical'] as int? ?? 0) == 1,
      brulureCervicoFaciale:
          (map['brulure_cervico_faciale'] as int? ?? 0) == 1,
      brulureLocalisation: map['brulure_localisation'] as String?,
      dysmorphieCranioFaciale:
          (map['dysmorphie_cranio_faciale'] as int? ?? 0) == 1,
      dysmorphieLocalisation: map['dysmorphie_localisation'] as String?,
      tumeurCervicofaciale:
          (map['tumeur_cervicofaciale'] as int? ?? 0) == 1,
      tumeurLocalisation: map['tumeur_localisation'] as String?,
      ronflement: (map['ronflement'] as int? ?? 0) == 1,
      dysphonie: (map['dysphonie'] as int? ?? 0) == 1,
      dysphagie: (map['dysphagie'] as int? ?? 0) == 1,
      acteOperatoire: map['acte_operatoire'] as String?,
      scoreStopbang: map['score_stopbang'] as int?,
      mallampati: map['mallampati'] as String?,
      dtm: map['dtm'] as String?,
      ouvertureBuccale: map['ouverture_buccale'] as String?,
      tourDeCou: map['tour_de_cou'] as String?,
      mobiliteCervicale: map['mobilite_cervicale'] as String?,
      macroglossie: (map['macroglossie'] as int? ?? 0) == 1,
      scoreAsa: map['score_asa'] as String?,
      intubationPrevue: map['intubation_prevue'] as String?,
      typeIntubation: map['type_intubation'] as String?,
      nombreTentatives: map['nombre_tentatives'] as int?,
      videolaryngoscope: (map['videolaryngoscope'] as int? ?? 0) == 1,
      guideEichmann: (map['guide_eichmann'] as int? ?? 0) == 1,
      scoreCormack: map['score_cormack'] as String?,
      intubationDifficileReelle:
          (map['intubation_difficile_reelle'] as int? ?? 0) == 1,
      complications: map['complications'] as String?,
      photoPaths: decodedPhotos,
      audioPath: map['audio_path'] as String?,
    );
  }

