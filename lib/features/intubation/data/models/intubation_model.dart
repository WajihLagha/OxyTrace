import 'dart:convert';

import '../../domain/entities/intubation_entity.dart';

class IntubationModel extends IntubationEntity {
  const IntubationModel({
    super.id,
    required super.patientId,
    required super.createdAt,
    required super.updatedAt,
    super.antecedentIntubationDifficile,
    super.saos,
    super.diabete,
    super.goitre,
    super.maladieRhumatismale,
    super.traumatismeCervical,
    super.brulureCervicoFaciale,
    super.brulureLocalisation,
    super.dysmorphieCranioFaciale,
    super.dysmorphieLocalisation,
    super.tumeurCervicofaciale,
    super.tumeurLocalisation,
    super.ronflement,
    super.dysphonie,
    super.dysphagie,
    super.acteOperatoire,
    super.scoreStopbang,
    super.mallampati,
    super.dtm,
    super.ouvertureBuccale,
    super.tourDeCou,
    super.mobiliteCervicale,
    super.macroglossie,
    super.scoreAsa,
    super.intubationPrevue,
    super.typeIntubation,
    super.nombreTentatives,
    super.videolaryngoscope,
    super.guideEichmann,
    super.scoreCormack,
    super.intubationDifficileReelle,
    super.complications,
    super.photoPaths,
    super.audioPath,
  });

  factory IntubationModel.fromEntity(IntubationEntity entity) {
    return IntubationModel(
