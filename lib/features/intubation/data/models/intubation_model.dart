      patientId: entity.patientId,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
      antecedentIntubationDifficile: entity.antecedentIntubationDifficile,
      saos: entity.saos,
      diabete: entity.diabete,
      goitre: entity.goitre,
      maladieRhumatismale: entity.maladieRhumatismale,
      traumatismeCervical: entity.traumatismeCervical,
      brulureCervicoFaciale: entity.brulureCervicoFaciale,
      brulureLocalisation: entity.brulureLocalisation,
      dysmorphieCranioFaciale: entity.dysmorphieCranioFaciale,
      dysmorphieLocalisation: entity.dysmorphieLocalisation,
