        mobiliteCervicale: mobiliteCervicale,
        macroglossie: macroglossie,
        scoreAsa: scoreAsa,
        intubationPrevue: intubationPrevue,
        typeIntubation: typeIntubation,
        nombreTentatives: nombreTentatives,
        videolaryngoscope: videolaryngoscope,
        guideEichmann: guideEichmann,
        scoreCormack: scoreCormack,
        intubationDifficileReelle: intubationDifficileReelle,
        complications: complications,
        clearComplications: clearComplications,
        photoPaths: photoPaths,
        audioPath: audioPath,
        clearAudioPath: clearAudioPath,
      ),
    );
  }
}
